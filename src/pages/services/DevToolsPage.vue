<template>
  <service-detail-layout
    :service="service"
    action-label="デベロッパーツールを開く"
  >
    <h2>どんなサイトか</h2>
    <p>
      「デベロッパーツール」は、プログラミングやWeb開発の作業中に「ちょっと確認したい」場面で使える、小さなツールを集めたサイトです。今は文字数カウンター、JSON整形、JWTデコーダーの3つがあります。
    </p>
    <p>
      どのツールも、入力した内容はブラウザの中だけで処理し、サーバーには送信しません。登録も不要で、開いてすぐに使えます。
    </p>

    <h2>文字数カウンター</h2>
    <p>
      テキストを入力すると、その場で文字数を数えて表示します。ブログの記事やSNSの投稿、フォームの入力欄など、文字数に上限がある文章を書くときに使えます。
    </p>
    <h3>絵文字も見た目どおり1文字と数える</h3>
    <p>
      JavaScriptの文字列の長さ（<code>length</code>）で数えると、「👍」は2文字、「👨‍👩‍👧」のような家族の絵文字は8文字と数えられてしまいます。これは、コンピューターの内部では、1つに見える文字が複数の部品の組み合わせで表されていることがあるためです。このツールでは、ブラウザの<code>Intl.Segmenter</code>を使って、人が見て1文字だと感じる単位（書記素）で数えるので、絵文字や濁点を組み合わせた文字も1文字になります。
    </p>
    <p>
      空白や改行も1文字として数えます。サービスによっては改行や絵文字の数え方が違うことがあるので、上限ぎりぎりの場合は投稿先の仕様も確認してください。
    </p>

    <h2>JSON整形</h2>
    <p>
      1行に詰まったJSONを貼り付けて「整形」を押すと、2文字のインデントを付けて読みやすく並べ直します。APIのレスポンスやログに出力されたJSONの中身を確認するときに便利です。
    </p>
    <p>入力例と整形後の結果：</p>
    <pre class="code-sample">{{ jsonSample }}</pre>
    <h3>使うときの注意</h3>
    <ul>
      <li>
        JSONとして正しくない入力（末尾の余分なカンマ、コメント、シングルクォートで囲んだ文字列など）は、「無効なJSONです」と表示されます。
      </li>
      <li>同じキーが2回出てくる場合は、後のほうの値だけが残ります。</li>
      <li>
        9007199254740991（2の53乗−1）を超える大きな整数は、JavaScriptの数値の精度の都合で、下の桁が変わって表示されることがあります。IDなどの大きな数値を確認するときは注意してください。
      </li>
    </ul>

    <h2>JWTデコーダー</h2>
    <p>
      JWT（JSON Web
      Token）は、ログイン後の認証などで使われる、「ヘッダー」「ペイロード」「署名」の3つの部分を「.」でつないだ文字列です。このツールにJWTを貼り付けて「デコード」を押すと、ヘッダーとペイロードの中身を読みやすいJSONにして表示します。
    </p>
    <ul>
      <li>
        ペイロードに有効期限（<code>exp</code>）があれば、日本時間の日時に変換して表示し、すでに期限が切れているかどうかも示します。
      </li>
      <li>
        署名はそのまま表示するだけで、検証はしていません。トークンが改ざんされていないかを確かめる用途には使えません。
      </li>
    </ul>
    <h3>JWTの中身は誰でも読める</h3>
    <p>
      JWTのヘッダーとペイロードは、Base64URLという方式で文字を置き換えているだけで、暗号化はされていません。このツールで中身が読めるのと同じように、トークンを手に入れた人は誰でも中身を読めます。パスワードなどの秘密の情報をペイロードに入れないようにしましょう。
    </p>
    <p>
      また、本番環境で使っているトークンは、それだけでログインできてしまう場合があります。このツールはサーバーに送信しませんが、一般に、本物のトークンを信頼できないWebサイトに貼り付けるのは避けてください。
    </p>

    <h2>工夫した点</h2>
    <h3>ツールを足しやすい作り</h3>
    <p>
      ツールの名前・説明・URLは1つの一覧にまとめ、サイドバーのメニュー、トップページのカード、検索エンジン向けのサイトマップを、すべてその一覧から自動で作っています。新しいツールを追加するときは、ページを作って一覧に1行足すだけで、メニューなどへの登録漏れが起きません。
    </p>
    <h3>処理と画面を分けてテストする</h3>
    <p>
      文字数を数える処理、JSONを整形する処理、JWTを読み取る処理は、画面とは別の関数にして、自動テストで確かめています。たとえばJWTデコーダーは、期限切れの判定に使う「現在時刻」を外から渡せるようにして、テストのたびに結果が変わらないようにしています。
    </p>
    <h3>静的なサイトとして公開</h3>
    <p>
      すべての処理がブラウザで完結するので、サーバーを持たない静的なサイトとして書き出して公開しています。動かすための費用がかからず、表示も速くなります。
    </p>

    <h2>使用技術</h2>
    <ul>
      <li>フレームワーク：Next.js（App Router、静的エクスポート）+ React</li>
      <li>言語：TypeScript</li>
      <li>UI：MUI（Material UI）、ダークモードにも対応</li>
      <li>テスト：Vitest</li>
    </ul>
  </service-detail-layout>
