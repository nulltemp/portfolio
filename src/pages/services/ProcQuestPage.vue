<template>
  <service-detail-layout :service="service" action-label="proc-questで遊ぶ">
    <h2>どんなゲームか</h2>
    <p>
      「proc-quest」は、マップが毎回自動で生成される、コマンド選択式のターン制ゲームです。マップはマス目ではなく、点（ノード）と線（エッジ）でつながった「グラフ」の形をしていて、プレイヤーは線でつながった隣のノードへ1ターンに1歩ずつ移動しながら、マップのどこかにいる敵のボスを目指します。
    </p>
    <p>
      ボスを倒せばクリア、自分の戦力が尽きればゲームオーバーです。1ターンごとに自分の戦力は少しずつ減り、敵の戦力は少しずつ増えていくので、寄り道して戦力を蓄えるか、早めにボスへ挑むかの見極めがポイントになります。登録は不要で、ブラウザを開けばすぐに遊べます。
    </p>

    <h2>遊び方</h2>
    <ol>
      <li>
        スタート画面でマップの大きさ（ノード数8〜80）を選び、「スタート」を押します。シード値を入力すると、同じマップを再現できます。
      </li>
      <li>
        マップ上の隣接するノードをクリック（スマホではタップ）すると、そのノードへ移動します。
      </li>
      <li>
        移動のほかに、「休息」で戦力を回復したり、手に入れたアイテムを使ったりもできます。どの行動も1ターンを消費します。
      </li>
      <li>
        ボスのノードに着いたとき、自分の戦力が敵の戦力以上なら勝利です。足りなければ反撃を受けますが、戦力を立て直してから何度でも挑み直せます。
      </li>
    </ol>
    <p>
      進行状況は自動でブラウザに保存され、次に開いたときに「続きから」で再開できます。セーブデータをファイルとして書き出し、読み込むこともできます。
    </p>

    <h2>ノードの種類</h2>
    <v-table density="compact">
      <thead>
        <tr>
          <th>ノード</th>
          <th>着いたときに起きること</th>
        </tr>
      </thead>
      <tbody>
        <tr v-for="node in nodes" :key="node.name">
          <td class="text-no-wrap">{{ node.name }}</td>
          <td>{{ node.effect }}</td>
        </tr>
      </tbody>
    </v-table>
    <p>
      戦闘・イベント・宝箱の効果は最初に訪れたときだけ起こります。同じノードを往復して戦力を稼ぐことはできません。
    </p>

    <h2>アイテム</h2>
    <ul>
      <li><strong>パワードリンク</strong>：使うと戦力が回復します。</li>
      <li>
        <strong>ガーディアンウォード</strong
        >：使うとシールドを張り、次に受けるダメージを1回分防ぎます。
      </li>
    </ul>
    <p>
      アイテムは宝箱で手に入れても、その場では使われず所持品に入ります。ボス戦の直前にシールドを張るなど、使うタイミングを自分で選べます。
    </p>

    <h2>作った理由</h2>
    <p>
      ゲームを遊ぶたびに違う地形・違う展開になる「手続き型生成（プロシージャル生成）」に興味があり、その土台となるマップ生成から作り始めたゲームです。最終的には、数時間で区切りをつけることも、同じ世界で長く遊び続けることもできる、勢力どうしがせめぎ合うストラテジー寄りのゲームを目指しています。
    </p>

    <h2>工夫した点</h2>
    <h3>必ずつながっていて、遠回りもできるマップ</h3>
    <p>
      マップは、ランダムに配置した点を、まず「最小全域木」と呼ばれる方法で1本の木としてつなぎ、どのノードからでもボスへたどり着けることを保証しています。そのうえで、近くのノードどうしにも線を足して、行き止まりばかりにならない自然な形にしています。スタート地点とボスは、できるだけ離れた2点に置いています。
    </p>
    <h3>シード値で同じマップと展開を再現できる</h3>
    <p>
      乱数はすべてシード値から計算しているので、同じシード値なら、マップだけでなく戦闘やイベントの結果まで同じになります。不具合の再現や、友達と同じマップで遊ぶのに使えます。
    </p>
    <h3>ボットに遊ばせてバランスを測る</h3>
    <p>
      ゲームのルールは画面と切り離した関数として書いてあり、ボット（自動で遊ぶプログラム）に何百回も遊ばせて勝率やクリアまでのターン数を集計できるようにしています。たとえば、現在のルールでは「休息し続ければ必ず勝てる」ことがこの集計で分かっており、今後のルール見直しで直す予定です。
    </p>
    <h3>スマホでも遊びやすく</h3>
    <p>
      スマホの画面ではノードが小さく表示されるため、タップした位置に一番近いノードを選ぶようにしています。また、隣接していないノードをタップしたときはターンを消費せず、そのノードの情報を表示するだけにしています。
    </p>

    <h2>使用技術</h2>
    <ul>
      <li>言語：TypeScript</li>
      <li>画面：Vite（フレームワークは使わず、マップはSVGで描画）</li>
      <li>配信：Cloudflare Workers（静的ファイルのみ）</li>
      <li>テスト：Node.js 標準のテストランナー（node:test）</li>
    </ul>
    <p>
      マップ生成とゲームのルールは、ブラウザ版とターミナルで遊べるコマンドライン版で共通のコードを使っています。画面は日本語と英語に対応しています。
    </p>

    <h2>今後の予定</h2>
    <p>
      現在のルールや数値は、ゲームとして遊べる形にするための仮のものです。今後は、ノードごとに支配する勢力を持たせ、複数の勢力が自分で動き回る本格的な勢力システムを作っていく予定です。不具合や要望があれば、トップページのお問い合わせフォームからお知らせください。
    </p>
  </service-detail-layout>
</template>

