<template>
  <service-detail-layout :service="service" action-label="proc-questで遊ぶ">
    <h2>どんなゲームか</h2>
    <p>
      「proc-quest」は、マップが毎回自動で生成される、コマンド選択式のターン制RPGです。マップはマス目ではなく、点（ノード）と線（エッジ）でつながった「グラフ」の形をしていて、プレイヤーは線でつながった隣のノードへ1ターンに1歩ずつ移動しながら、マップのどこかにいる敵のボスを目指します。
    </p>
    <p>
      ボスを倒せばクリア、自分のHPが尽きればゲームオーバーです。1ターンごとにHPは少しずつ減っていくので、戦闘やダンジョンで経験値・装備・ゴールドを集めて強くなるか、早めにボスへ挑むかの見極めがポイントになります。登録は不要で、ブラウザを開けばすぐに遊べます。
    </p>

    <h2>遊び方</h2>
    <ol>
      <li>
        スタート画面でマップの大きさ（ノード数8〜80）を選び、「スタート」を押します。シード値を入力すると、同じマップを再現できます。
      </li>
      <li>
        画面のコマンドメニュー（移動・アイテム・装備・スキルなど）から行動を選びます。マップ上の隣接するノードをクリック（スマホではタップ）しても移動できます。メニューはキーボード（数字キーとEsc）でも操作できます。
      </li>
      <li>
        戦闘のノードやボスのノードに着くと戦闘が始まり、「たたかう」「スキル」「にげる」「アイテム」から行動を選びます。それぞれの選択肢には、与えるダメージや受けるダメージの見込みが表示されます。
      </li>
      <li>
        ボス戦は何ラウンドも続く戦いで、ボスは次の行動（攻撃・力をためる・防御など）を予告します。力をためた次のラウンドには強烈な一撃が来るので、予告を見てスキルやアイテムで備えましょう。
      </li>
    </ol>
    <p>
      進行状況は自動でブラウザに保存され、次に開いたときに「続きから」で再開できます。セーブデータをファイルとして書き出し、読み込むこともできます。
    </p>

    <h2>成長と街</h2>
    <ul>
      <li>
        <strong>レベル</strong
        >：戦闘で経験値を得てレベルが上がると、HP・攻撃力・防御力・最大MPが上がります。
      </li>
      <li>
        <strong>装備</strong
        >：武器と防具は宝箱や街の店で手に入り、身に着けると攻撃力・防御力が上がります。スキルが使えるようになる装備もあります。
      </li>
      <li>
        <strong>スキル</strong
        >：MPを使う技です。攻撃・回復・防御を固める・敵を眠らせるの4種類があり、レベルが上がるか、街の修練場でゴールドを払うと覚えられます。
      </li>
      <li>
        <strong>街</strong
        >：戦闘や宝箱で集めたゴールドを使って、宿屋でHPとMPを回復したり、店でアイテムや装備を買ったり、いらない装備を売ったりできます。
      </li>
    </ul>

    <h2>ノードの種類</h2>
    <v-table density="compact">
      <thead>
        <tr>
          <th>ノード</th>
          <th>着いたときに起きること</th>
        </tr>
      </thead>
      <tbody>
        <tr v-for="node in nodes" :key="node.name">
          <td class="text-no-wrap">{{ node.name }}</td>
          <td>{{ node.effect }}</td>
        </tr>
      </tbody>
    </v-table>
    <p>
      戦闘・イベント・宝箱は最初に訪れたときだけ起こります。同じノードを往復して稼ぐことはできません。
    </p>

    <h2>アイテム</h2>
    <ul>
      <li><strong>回復ドリンク</strong>：使うとHPが回復します。</li>
      <li>
        <strong>ガーディアンウォード</strong
        >：使うとシールドを張り、次に受けるダメージを1回分防ぎます。
      </li>
    </ul>
    <p>
      アイテムは宝箱や店で手に入れても、その場では使われず所持品に入ります。ボスの強烈な一撃に合わせてシールドを張るなど、使うタイミングを自分で選べます。
    </p>

    <h2>使用技術</h2>
    <ul>
      <li>言語：TypeScript</li>
      <li>画面：Vite（フレームワークは使わず、マップはSVGで描画）</li>
      <li>配信：Cloudflare Workers（静的ファイルのみ）</li>
      <li>テスト：Node.js 標準のテストランナー（node:test）</li>
    </ul>
    <p>
      マップ生成とゲームのルールは画面と切り離した純粋な関数として書いていて、ルールの調整には、いくつかの方針で自動的に遊ぶボットを何百回も対戦させるシミュレーションを使っています。画面は日本語と英語に対応しています。
    </p>
  </service-detail-layout>
</template>

<script>
import ServiceDetailLayout from "@/components/ServiceDetailLayout.vue";
