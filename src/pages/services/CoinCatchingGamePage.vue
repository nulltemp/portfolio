<template>
  <service-detail-layout
    :service="service"
    action-label="コインキャッチゲームで遊ぶ"
  >
    <h2>どんなゲームか</h2>
    <p>
      「コインキャッチゲーム」は、画面の下にいるプレイヤー（青いバー）を左右に動かして、上から降ってくるコインをキャッチするシンプルなアクションゲームです。制限時間は20秒で、その間に何枚のコインを取れるかを競います。1回のプレイが短いので、ちょっとした空き時間に遊べます。
    </p>
    <p>
      ブラウザだけで動き、インストールや登録は必要ありません。PCではキーボードかマウス、スマホやタブレットではタッチで操作できます。
    </p>

    <h2>遊び方</h2>
    <h3>操作方法</h3>
    <ul>
      <li><strong>PC</strong>：← / → キーでプレイヤーを左右に動かします。</li>
      <li>
        <strong>マウス・タッチ</strong
        >：画面を押している間、プレイヤーが押した位置に向かって動きます。離れた位置ほど速く動き、近づくとゆっくり止まります。
      </li>
    </ul>
    <h3>ルール</h3>
    <ol>
      <li>コインにプレイヤーが触れるとスコアが1点増えます。</li>
      <li>
        5秒ごとにレベルが上がり、コインの出る間隔が短く、落ちる速さが速くなります。
      </li>
      <li>
        残り時間が0になるとゲームオーバーです。「もう一度プレイ」を押すと最初から遊べます。
      </li>
    </ol>
    <p>
      自己ベストはハイスコアとしてブラウザに保存され、次に遊ぶときも画面の左上に表示されます。記録を更新すると、ゲームオーバーの画面に「New
      Record!」と表示されます。
    </p>

    <h2>レベルの上がり方</h2>
    <p>20秒のあいだに、難しさは次のように4段階で変わります。</p>
    <v-table density="compact">
      <thead>
        <tr>
          <th>レベル</th>
          <th>経過時間</th>
          <th>コインの出る間隔</th>
          <th>落ち始めの速さ（ピクセル/秒）</th>
        </tr>
      </thead>
      <tbody>
        <tr v-for="row in levels" :key="row.level">
          <td>Lv {{ row.level }}</td>
          <td>{{ row.time }}</td>
          <td>{{ row.interval }}</td>
          <td>{{ row.speed }}</td>
        </tr>
      </tbody>
    </v-table>
    <p>
      コインは重力で加速しながら落ちてくるので、レベルが上がると、画面の上から下まであっという間に落ちてきます。
    </p>

    <h2>高得点のコツ</h2>
    <ul>
      <li>
        コインを1枚取ると、すぐに画面の上へ新しいコインが1枚追加されます。取れば取るほど画面のコインが増えるので、序盤に取りこぼさないことが大切です。
      </li>
      <li>
        後半（Lv
        3以降）はコインが速く落ちるので、落ちてくるコインを追いかけるより、次に落ちてきそうな位置へ先に動いておくと取りやすくなります。
      </li>
      <li>
        タッチ操作は、プレイヤーの少し先を押し続けると、動きすぎずに位置を合わせられます。
      </li>
    </ul>

    <h2>作った理由</h2>
    <p>
      ゲームエンジン「Phaser」を使ったブラウザゲーム作りを一通り試すために作りました。画像の読み込み、物理演算による落下と当たり判定、タイマーによる時間制限、スコアの表示と保存といった、ゲームに必要な基本の要素を、できるだけ小さな題材で組み立てています。
    </p>

    <h2>工夫した点</h2>
    <h3>スマホでも遊べるようにした</h3>
    <p>
      ゲーム画面は800×600の大きさで作り、画面の大きさに合わせて縦横比を保ったまま拡大・縮小しています。キーボードが無いスマホやタブレットのために、押した位置へプレイヤーが追いかけていく操作を加えました。押した位置との距離に応じて速さを変えているので、目的の位置で行き過ぎずに止まります。
    </p>
    <h3>難易度を時間で上げる</h3>
    <p>
      最初は20秒間ずっと同じ速さで、単調になりがちでした。そこで、5秒ごとにレベルを上げ、コインの出現間隔と落下の速さを段階的に変えるようにしました。レベルごとの値は定数にまとめてあり、遊びながら調整できるようにしています。
    </p>
    <h3>ハイスコアの保存</h3>
    <p>
      ハイスコアはブラウザのlocalStorageに保存しています。プライベートブラウズなどでlocalStorageが使えない環境では、保存をあきらめてそのまま遊べるようにしました。
    </p>

    <h2>使用技術</h2>
    <ul>
      <li>
        ゲームエンジン：Phaser 4（Arcade Physics で落下と当たり判定を処理）
      </li>
      <li>言語：TypeScript</li>
      <li>ビルド：Vite</li>
      <li>公開：独自ドメインの静的サイト</li>
    </ul>

    <h2>今後の予定</h2>
    <p>
      今はコインを取るだけのシンプルな内容なので、取ってはいけない爆弾やコンボによる得点の倍率、効果音やBGM、取ったときの演出などを加えて、繰り返し遊びたくなるゲームにしていく予定です。
    </p>
  </service-detail-layout>
</template>

